// TasmoFlow automations, Berry engine: the automations (tf_auto.json on the gateway, the source of
// truth) turned into Berry (/tf_auto.be), which the gateway runs at boot through
// extension/tf_autolib.be, browser closed. The generator runs here, in the browser, to save the
// gateway's memory (specification: "Moteur d'actions"). The generated Berry is shown read only.
//
// An automation:
//   { id, name, on,                                   on: false = kept, not generated
//     when: [trigger, ...],                           any of them starts it
//     cond: null | { mode: 'all' | 'any', items: [state, ...] },
//     then: [step, ...] }
// trigger: { src: 'zigbee', addr, name, attr, op, value }   a Zigbee attribute (op '' = any value)
//          { src: 'tuya', dev, dp, op, value }               a DP of a Tuya device
//          { src: 'tuyaconn', dev, on }                     a Tuya device connecting (on) or not
//          { src: 'rule', pat }                             any Tasmota trigger (`Power1#State=1`)
// state:   { src: 'zigbee', addr, attr, op, value } | { src: 'tuya', dev, dp, op, value }
// step:    { cmd }                                          a Tasmota command (Backlog included)
//          { wait: seconds, restart }                       the next steps later; restart: a new
//                                                           trigger starts the delay again
// Rules a Tasmota rule set can hold stay in the sentence editor (Rule1 to Rule3); these are what
// it cannot do: a given Tuya device's DP, conditions on several devices, delays that restart.

export const OPS = ['=', '!=', '<', '<=', '>', '>='];

// a Berry string literal (UTF-8 kept as is)
export const q = s => '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\r/g, '\\r') + '"';

const isNamed = t => t.name && t.name !== t.addr && !/^0x[0-9a-f]{4}$/i.test(t.name);

// the Berry test of a comparison on value `v` (an expression), or null when any value goes
const test = (v, op, value) => (op ? 'a.cmp(' + v + ', ' + q(op) + ', ' + q(value == null ? '' : value) + ')' : null);

function stateExpr(s) {
  const v = s.src === 'zigbee' ? 'a.zbget(' + q(s.addr) + ', ' + q(s.attr) + ')' : 'a.tuyaget(' + q(s.dev) + ', ' + q(String(s.dp)) + ')';
  return test(v, s.op || '=', s.value);
}

// the steps from `k` on, as Berry lines (indented by `pad`)
function steps(auto, list, k, pad) {
  const out = [];
  for (let i = k; i < list.length; i++) {
    const st = list[i];
    if (st.wait != null) {
      const ms = Math.max(0, Math.round(+st.wait * 1000)) || 0;
      out.push(pad + 'a.later(' + q('tfa_' + auto.id + '_' + i) + ', ' + ms + ', def ()');
      out.push(...steps(auto, list, i + 1, pad + '  '));
      out.push(pad + 'end, ' + (st.restart ? 'true' : 'false') + ')');
      return out;
    }
    if (st.cmd && st.cmd.trim()) out.push(pad + 'a.cmd(' + q(st.cmd.trim()) + ')');
  }
  return out;
}

// the registration of one trigger, calling `run`
function trigger(t, run) {
  const call = v => { const c = test(v, t.op, t.value); return c ? 'if ' + c + ' ' + run + '() end' : run + '()'; };
  if (t.src === 'zigbee') {
    const keys = [t.addr, ...(isNamed(t) ? [t.name] : [])].map(q).join(', ');
    return 'a.zb([' + keys + '], ' + q(t.attr) + ', def (v) ' + call('v') + ' end)';
  }
  if (t.src === 'tuya') return 'a.tuya(' + q(t.dev) + ', ' + q(String(t.dp)) + ', def (v) ' + call('v') + ' end)';
  if (t.src === 'tuyaconn') return 'a.tuyaconn(' + q(t.dev) + ', ' + (t.on ? 'true' : 'false') + ', def (v) ' + run + '() end)';
  if (t.src === 'rule' && t.pat && t.pat.trim()) return 'a.on(' + q(t.pat.trim()) + ', def (v) ' + run + '() end)';
  return null;
}

// Problems that keep an automation from being generated: [text keys] (empty: fine)
export function autoErrors(a) {
  const errs = [];
  if (!(a.when || []).some(t => trigger(t, 'r'))) errs.push('au_noTrigger');
  if (!(a.then || []).some(s => s.cmd && s.cmd.trim())) errs.push('au_noAction');
  for (const t of a.when || []) if (t.op && !OPS.includes(t.op)) errs.push('au_badOp');
  for (const s of (a.cond && a.cond.items) || []) if (s.op && !OPS.includes(s.op)) errs.push('au_badOp');
  if ((a.then || []).some(s => s.wait != null && !(+s.wait >= 0))) errs.push('au_badWait');
  return [...new Set(errs)];
}

// The Berry of the enabled automations that have no error: the text of /tf_auto.be
export function generate(autos) {
  const out = ['# TasmoFlow automations: generated by the interface from tf_auto.json, do not edit', 'return def (a)'];
  let n = 0;
  for (const a of autos || []) {
    if (a.on === false || autoErrors(a).length) continue;
    n++;
    const run = 'r' + n;
    out.push('  # ' + String(a.name || a.id).replace(/[\r\n]/g, ' '));
    out.push('  var ' + run + ' = def ()');
    const conds = ((a.cond && a.cond.items) || []).map(stateExpr).filter(Boolean);
    if (conds.length) out.push('    if !(' + conds.join(a.cond.mode === 'any' ? ' || ' : ' && ') + ')    return    end');
    out.push(...steps(a, a.then || [], 0, '    '));
    out.push('  end');
    for (const t of a.when || []) { const r = trigger(t, run); if (r) out.push('  ' + r); }
  }
  out.push('end', '');
  return out.join('\n');
}

// a new automation's id: short, unique among `autos`
export function newId(autos) {
  const used = new Set((autos || []).map(a => a.id));
  for (let i = 1; ; i++) if (!used.has('a' + i)) return 'a' + i;
}
